/**
 * The public /demo intake — a sample personal-injury matter.
 *
 * This module is isomorphic (safe to import from client and server code): the
 * demo page renders its form from DEMO_INTAKE_FIELDS, and the server handler
 * summarizes against the same definitions, so the two can never drift.
 *
 * PRIVACY: the demo is storage-free by design. The submit handler validates,
 * summarizes, and returns — it makes no database calls at all. Nothing a
 * visitor enters is saved or sent anywhere.
 */

import type { IntakeField } from "./types";

export const DEMO_INTAKE_FIELDS: IntakeField[] = [
  {
    id: "client_name",
    type: "text",
    label: "Your full name",
    placeholder: "e.g. Jane Client (optional)",
  },
  {
    id: "contact_info",
    type: "text",
    label: "Phone or email",
    placeholder: "(555) 123-4567 or you@example.com (optional)",
  },
  {
    id: "incident_date",
    type: "date",
    label: "Date of incident",
    required: true,
  },
  {
    id: "incident_description",
    type: "textarea",
    label: "Describe what happened",
    placeholder:
      "Where you were, how it happened, and what happened next — as much detail as you can.",
    required: true,
  },
  {
    id: "injuries_damages",
    type: "textarea",
    label: "Injuries and damages",
    placeholder:
      "Injuries, medical treatment, missed work, property damage, other losses.",
    required: true,
  },
];

/**
 * Deterministic fallback summary (same role as the template fallback for
 * documents): used when no OpenAI key is configured. Honest and clearly
 * labeled as template-generated by the demo page.
 */
export function demoTemplateSummary(d: Record<string, string>): string {
  const clipped = (v: string) =>
    v.length > 300 ? `${v.slice(0, 300)}...` : v;

  const lines: string[] = ["Matter: Personal injury — client intake"];
  if (d.client_name) lines.push(`Client: ${d.client_name}`);
  if (d.contact_info) lines.push(`Contact: ${d.contact_info}`);
  if (d.incident_date) lines.push(`Incident date: ${d.incident_date}`);
  if (d.incident_description)
    lines.push(`What happened: ${clipped(d.incident_description)}`);
  if (d.injuries_damages)
    lines.push(`Injuries and damages: ${clipped(d.injuries_damages)}`);
  lines.push(
    "Suggested next steps: confirm the statute-of-limitations deadline, request medical records, and identify all insurance carriers involved.",
  );
  return lines.join("\n");
}
